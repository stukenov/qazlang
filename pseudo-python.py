class ЗапросНаПокупку:
    def __init__(self, код_материала, количество, группа_закупок, завод, склад):
        self.код_материала = код_материала
        self.количество = количество
        self.группа_закупок = группа_закупок
        self.завод = завод
        self.склад = склад

    def СоздатьЗапросНаПокупку(self):
        try:
            # Здесь будет логика для обращения к SAP API для создания запроса на покупку.
            # Но поскольку это только имитация, 
            # представим что мы отправляем данные и получаем номер запроса.
            номер_запроса = '123456'  # Имитация успешного ответа API.
            return номер_запроса
        except Exception as e:
            # В случае ошибки вернуть сообщение об ошибке.
            return f'Ошибка при создании запроса на покупку: {str(e)}'


def ОтобразитьФормуСозданияЗапросаНаПокупку():
    print("Пожалуйста, введите следующие данные:")
    # Имитация полей ввода для пользователя.
    # В реальной программе это будет GUI или веб-форма.
    код_материала = input("Код материала: ")
    количество = input("Количество: ")
    группа_закупок = input("Группа закупок: ")
    завод = input("Завод: ")
    склад = input("Склад: ")
    print("Нажмите кнопку 'Создать запрос на покупку' для продолжения...")

    # Имитация нажатия кнопки вызовом функции.
    ОбработатьСозданиеЗапросаНаПокупку({
        'код_материала': код_материала,
        'количество': количество,
        'группа_закупок': группа_закупок,
        'завод': завод,
        'склад': склад,
    })


def ОтобразитьРезультат(результат):
    if результат.startswith('Ошибка'):
        print(f'Ошибка при создании запроса на покупку: {результат}')
    else:
        print(f'Запрос на покупку №{результат} успешно создан.')


def ОбработатьСозданиеЗапросаНаПокупку(данные_формы):
    запрос = ЗапросНаПокупку(
        данные_формы['код_материала'],
        данные_формы['количество'],
        данные_формы['группа_закупок'],
        данные_формы['завод'],
        данные_формы['склад'],
    )
    результат = запрос.СоздатьЗапросНаПокупку()
    ОтобразитьРезультат(результат)


# Симуляция запуска программы.
if __name__ == "__main__":
    ОтобразитьФормуСозданияЗапросаНаПокупку()